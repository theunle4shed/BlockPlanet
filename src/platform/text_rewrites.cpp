std::uint64_t text_fingerprint(const std::string& text) {
    std::uint64_t hash = 0xcbf29ce484222325ull;  // FNV-1a, 64-bit
    for (unsigned char c : text) {
        hash ^= c;
        hash *= 0x100000001b3ull;
    }
    return hash;
}

